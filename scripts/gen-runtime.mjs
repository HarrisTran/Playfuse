// Bundle src/runtime thành chuỗi JS để Web UI (worker) dùng như CLI.
// Chạy tự động trước `npm run web` / `npm run web:build`.
import * as esbuild from 'esbuild';
import fs from 'node:fs';

const result = await esbuild.build({
    entryPoints: ['src/runtime/index.ts'],
    bundle: true,
    write: false,
    target: 'es2015',
    format: 'iife',
    globalName: '__pf',
    minify: true,
});

const code = result.outputFiles[0].text;
fs.writeFileSync(
    'src/runtime/bundle.generated.ts',
    `// AUTO-GENERATED by scripts/gen-runtime.mjs — do not edit.\nexport const DEFAULT_RUNTIME_CODE = ${JSON.stringify(code)};\n`
);
console.log(`[gen-runtime] runtime bundle: ${code.length} bytes`);
